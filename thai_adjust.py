def thai_to_precomposed(text: str) -> str:
    """Convert Thai text to pre-composed form using Hangul codepoints."""
    result = []
    i = 0
    while i < len(text):
        # Try matching longest sequence first (up to 4 chars)
        matched = False
        for length in range(min(4, len(text) - i), 0, -1):
            seq = tuple(ord(c) for c in text[i:i+length])
            if seq in THAI_TO_HANGUL:
                result.append(chr(THAI_TO_HANGUL[seq]))
                i += length
                matched = True
                break
        if not matched:
            result.append(text[i])
            i += 1
    return ''.join(result)


def precomposed_to_thai(text: str) -> str:
    """Convert pre-composed text (with Hangul) back to standard Thai."""
    result = []
    for char in text:
        code = ord(char)
        if code in HANGUL_TO_THAI:
            result.extend(chr(c) for c in HANGUL_TO_THAI[code])
        else:
            result.append(char)
    return ''.join(result)


